// PWA_START: web/index.html preloads files the engine fetches only after
// main.dart.js has run. A renamed font or asset would turn a preload into a
// wasted 404, so every preloaded path must map to a bundled source file.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

void main() {
  test('every asset preload in web/index.html points at a bundled file', () {
    final html = File('web/index.html').readAsStringSync();
    final hrefs = RegExp(r'<link rel="preload" href="(assets/[^"]+)"')
        .allMatches(html)
        .map((m) => m.group(1)!)
        .toList();
    expect(hrefs, isNotEmpty);

    final pubspec = File('pubspec.yaml').readAsStringSync();
    for (final href in hrefs) {
      final path = href.substring('assets/'.length);
      if (path == 'FontManifest.json' || path == 'AssetManifest.bin.json') {
        continue; // generated by flutter build
      }
      if (path == 'fonts/MaterialIcons-Regular.otf') continue; // Flutter SDK
      if (path == '.env.app') {
        // written by CI / tool/write_app_env.sh, not checked in
        expect(pubspec, contains('- .env.app'));
        continue;
      }
      if (path.startsWith('packages/cupertino_icons/')) {
        expect(pubspec, contains('cupertino_icons:'), reason: href);
        continue;
      }
      expect(File(path).existsSync(), isTrue, reason: '$href → $path');
      expect(pubspec, contains(path), reason: '$path is not a pubspec asset');
    }
  });

  test('asset preloads match the engine fetch (cors, low priority)', () {
    final html = File('web/index.html').readAsStringSync();
    for (final m in RegExp(r'<link rel="preload" href="assets/[^>]+>')
        .allMatches(html)) {
      expect(m.group(0), contains('as="fetch" crossorigin="anonymous"'));
      expect(m.group(0), contains('fetchpriority="low"'));
    }
  });
}
