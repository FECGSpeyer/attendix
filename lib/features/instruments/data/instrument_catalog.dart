List<CatalogInstrument> searchInstrumentCatalog(
  String query, {
  InstrumentFamily? family,
  bool voicesOnly = false,
}) {
  final normalizedQuery = normalizeCatalogName(query);
  final exact = <CatalogInstrument>[];
  final partial = <CatalogInstrument>[];
  for (final instrument in instrumentCatalog) {
    if (family != null && instrument.family != family) continue;
    if (voicesOnly && instrument.family != InstrumentFamily.voices) continue;
    final names = [
      instrument.nameDe,
      instrument.nameEn,
      ...instrument.aliases,
    ].map(normalizeCatalogName);
    if (normalizedQuery.isEmpty || names.contains(normalizedQuery)) {
      exact.add(instrument);
    } else if (names.any((name) => name.contains(normalizedQuery))) {
      partial.add(instrument);
    }
  }
  return List.unmodifiable([...exact, ...partial]);
}

/// Exact matching tolerates case, spacing, punctuation and German umlauts.
/// Part numbers and wildcard characters are preserved deliberately.
String normalizeCatalogName(String value) =>
    value
        .toLowerCase()
        .replaceAll('ä', 'ae')
        .replaceAll('ö', 'oe')
        .replaceAll('ü', 'ue')
        .replaceAll('ß', 'ss')
        .replaceAll(RegExp(r'[^\p{L}\p{N}*?]+', unicode: true), ' ')
        .trim();
