/// Musical family order used by both catalogue filters and new categories.
enum InstrumentFamily {
  strings,
  woodwinds,
  brass,
  percussion,
  keyboards,
  plucked,
  voices,
  folk;

  String label(String languageCode) => switch ((this, languageCode == 'en')) {
    (strings, false) => 'Streicher',
    (strings, true) => 'Strings',
    (woodwinds, false) => 'Holzbläser',
    (woodwinds, true) => 'Woodwinds',
    (brass, false) => 'Blechbläser',
    (brass, true) => 'Brass',
    (percussion, false) => 'Schlagwerk',
    (percussion, true) => 'Percussion',
    (keyboards, false) => 'Tasteninstrumente',
    (keyboards, true) => 'Keyboards',
    (plucked, false) => 'Zupfinstrumente',
    (plucked, true) => 'Plucked strings',
    (voices, false) => 'Stimmen',
    (voices, true) => 'Voices',
    (folk, false) => 'Volksinstrumente',
    (folk, true) => 'Folk instruments',
  };
}

/// A bundled instrument type. Local ensemble groups remain independent copies.
class CatalogInstrument {
  const CatalogInstrument({
    required this.id,
    required this.nameDe,
    required this.nameEn,
    required this.family,
    this.aliases = const [],
    this.tuning,
    this.clefs,
  });

  final String id;
  final String nameDe;
  final String nameEn;
  final InstrumentFamily family;
  final List<String> aliases;
  final String? tuning;
  final List<String>? clefs;

  String label(String languageCode) => languageCode == 'en' ? nameEn : nameDe;
}

