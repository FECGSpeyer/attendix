/// One separately selectable ensemble group within a preset.
class CatalogPresetEntry {
  const CatalogPresetEntry({
    required this.key,
    required this.instrumentId,
    required this.nameDe,
    required this.nameEn,
    this.synonyms = const [],
    this.selectedByDefault = true,
  });

  final String key;
  final String instrumentId;
  final String nameDe;
  final String nameEn;
  final List<String> synonyms;
  final bool selectedByDefault;

  String label(String languageCode) => languageCode == 'en' ? nameEn : nameDe;
}

class CatalogPreset {
  const CatalogPreset({
    required this.id,
    required this.nameDe,
    required this.nameEn,
    required this.tenantType,
    required this.entries,
  });

  final String id;
  final String nameDe;
  final String nameEn;
  final String tenantType;
  final List<CatalogPresetEntry> entries;

  String label(String languageCode) => languageCode == 'en' ? nameEn : nameDe;
}

