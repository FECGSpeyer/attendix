// DB_FIX: extracts the column names of every public table from the Ionic
// reference project into test/fixtures/db_columns.dart.
//
// Sources (union):
//   1. src/app/utilities/supabase.ts — generated types, `Tables.<t>.Row`
//   2. supabase/sql/*.sql — `CREATE TABLE` bodies and
//      `ALTER TABLE <t> ADD COLUMN` statements (newer than the generated
//      types, e.g. player.sort_order, tenants.duty_view)
//
// Usage:
//   dart run tool/db/extract_db_columns.dart [/path/to/ionic]
//   dart run tool/db/extract_db_columns.dart --types types.ts   (live schema)
// (default /home/user/ionic)
import 'dart:io';

void main(List<String> args) {
  final tables = <String, Set<String>>{};

  // `--types <file>`: the live schema from
  // `supabase gen types typescript --project-id <id> > types.ts`
  // instead of the Ionic snapshot (most exact source).
  if (args.length == 2 && args.first == '--types') {
    _parseGeneratedTypes(File(args[1]).readAsStringSync(), tables);
    _write(tables);
    return;
  }

  final ionic = args.isNotEmpty ? args.first : '/home/user/ionic';
  _parseGeneratedTypes(
      File('$ionic/src/app/utilities/supabase.ts').readAsStringSync(), tables);

  final sqlDir = Directory('$ionic/supabase/sql');
  if (sqlDir.existsSync()) {
    final files = sqlDir
        .listSync()
        .whereType<File>()
        .where((f) => f.path.endsWith('.sql'))
        .toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    for (final f in files) {
      _parseSql(f.readAsStringSync(), tables);
    }
  }

  // Columns that Ionic reads/writes (interfaces.ts) but that are neither in
  // the generated types nor in supabase/sql.
  for (final e in _extraColumns.entries) {
    tables.putIfAbsent(e.key, () => {}).addAll(e.value);
  }

  _write(tables);
}

void _write(Map<String, Set<String>> tables) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/db/extract_db_columns.dart — do not edit.')
    ..writeln('// Columns of the public tables of the Ionic Supabase schema')
    ..writeln('// (supabase.ts Row types + supabase/sql migrations).')
    ..writeln()
    ..writeln('const Map<String, Set<String>> kDbColumns = {');
  final names = tables.keys.toList()..sort();
  for (final t in names) {
    final cols = tables[t]!.toList()..sort();
    out.writeln("  '$t': {");
    for (final c in cols) {
      out.writeln("    '$c',");
    }
    out.writeln('  },');
  }
  out.writeln('};');

  final target = File('test/fixtures/db_columns.dart');
  target.parent.createSync(recursive: true);
  target.writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${names.length} tables to ${target.path}');
}

const Map<String, Set<String>> _extraColumns = {
  'songs': {'additional_fields'},
  'tenants': {'song_additional_fields'},
  // interfaces.ts NotificationConfig.push_and_telegram (notification.service)
  'notifications': {'push_and_telegram'},
};

void _parseGeneratedTypes(String src, Map<String, Set<String>> tables) {
  final lines = src.split('\n');
  // Only the first `public: { Tables: {` block (the file repeats `public`
  // further down for Constants).
  final start = lines.indexWhere((l) => l == '    Tables: {');
  final end = lines.indexWhere((l) => l == '    Views: {', start);
  if (start < 0 || end < 0) return;
  final tableRe = RegExp(r'^      (\w+): \{$');
  final colRe = RegExp(r'^          (\w+)\??: ');
  String? table;
  var inRow = false;
  for (var i = start + 1; i < end; i++) {
    final l = lines[i];
    final tm = tableRe.firstMatch(l);
    if (tm != null) {
      table = tm.group(1);
      inRow = false;
      continue;
    }
    if (l == '        Row: {') {
      inRow = true;
      continue;
    }
    if (inRow && l == '        }') {
      inRow = false;
      continue;
    }
    if (inRow && table != null) {
      final cm = colRe.firstMatch(l);
      if (cm != null) tables.putIfAbsent(table, () => {}).add(cm.group(1)!);
    }
  }
}

String _stripComments(String sql) => sql
    .replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), '')
    .split('\n')
    .map((l) {
      final i = l.indexOf('--');
      return i >= 0 ? l.substring(0, i) : l;
    })
    .join('\n');

const _ident = r'(?:"([^"]+)"|(\w+))';

String _identOf(Match m, int quoted, int plain) =>
    (m.group(quoted) ?? m.group(plain))!;

void _parseSql(String raw, Map<String, Set<String>> tables) {
  final sql = _stripComments(raw);

  // CREATE TABLE [IF NOT EXISTS] [public.]name ( ... );
  final createRe = RegExp(
    r'CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:public\.)?' + _ident + r'\s*\(',
    caseSensitive: false,
  );
  for (final m in createRe.allMatches(sql)) {
    final table = _identOf(m, 1, 2);
    final body = _balancedBody(sql, m.end - 1);
    if (body == null) continue;
    for (final part in _splitTopLevel(body)) {
      final p = part.trim();
      if (p.isEmpty) continue;
      final first = RegExp(r'^' + _ident).firstMatch(p);
      if (first == null) continue;
      final name = _identOf(first, 1, 2);
      const constraintWords = {
        'constraint', 'primary', 'unique', 'foreign', 'check', 'exclude', 'like',
      };
      if (first.group(1) == null && constraintWords.contains(name.toLowerCase())) {
        continue;
      }
      tables.putIfAbsent(table, () => {}).add(name);
    }
  }

  // ALTER TABLE [IF EXISTS] [ONLY] [public.]name ... ADD COLUMN [IF NOT EXISTS] col
  for (final stmt in sql.split(';')) {
    final am = RegExp(
      r'ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?(?:public\.)?' + _ident,
      caseSensitive: false,
    ).firstMatch(stmt);
    if (am == null) continue;
    final table = _identOf(am, 1, 2);
    final addRe = RegExp(
      r'ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?' + _ident,
      caseSensitive: false,
    );
    for (final c in addRe.allMatches(stmt.substring(am.end))) {
      tables.putIfAbsent(table, () => {}).add(_identOf(c, 1, 2));
    }
  }
}

String? _balancedBody(String s, int openIdx) {
  var depth = 0;
  for (var i = openIdx; i < s.length; i++) {
    if (s[i] == '(') depth++;
    if (s[i] == ')') {
      depth--;
      if (depth == 0) return s.substring(openIdx + 1, i);
    }
  }
  return null;
}

List<String> _splitTopLevel(String body) {
  final parts = <String>[];
  var depth = 0;
  var last = 0;
  for (var i = 0; i < body.length; i++) {
    final ch = body[i];
    if (ch == '(') depth++;
    if (ch == ')') depth--;
    if (ch == ',' && depth == 0) {
      parts.add(body.substring(last, i));
      last = i + 1;
    }
  }
  parts.add(body.substring(last));
  return parts;
}
