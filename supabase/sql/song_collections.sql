-- song_collections: Werke-Sammlungen (Beta "Noten-Bereich neu gedacht").
--
-- Every Werk lies in exactly one Sammlung. "Repertoire" is the default and
-- has no row: songs.collection_id is null. Own Sammlungen ("Einspielen",
-- "Streicher", "In Vorbereitung" ...) have a number prefix, a visibility
-- (all / leads / groups), whether their Werke can be put into a Termin
-- programme, and whether the public Werke link shows them.
--
-- The visibility is enforced here: a RESTRICTIVE select policy on songs
-- (the existing permissive policies stay untouched) only lets rows through
-- whose Sammlung the reader may see. Leads (roles 1 admin, 3 viewer,
-- 5 responsible) see every Sammlung of their tenant or of the tenant their
-- Werke are synced from; "groups" matches the reader's group by name, so it
-- also works in synced tenants (their groups have other ids). Anonymous
-- readers (public Werke link) only see Repertoire and Sammlungen that are
-- visible to all and have public_link on.
--
-- Additive and safe to run twice. Without it the app behaves as before
-- (it detects the missing table/column and hides every Sammlung feature).
-- Apply only after the store release (no production change before it).
--
-- Rollback:
--   drop policy if exists "songs_collection_visibility" on public.songs;
--   alter table public.songs drop column if exists collection_id;
--   drop function if exists public.song_collection_visible(bigint);
--   drop table if exists public.song_collections;

create table if not exists public.song_collections (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  name text not null,
  prefix text not null default '',
  visibility text not null default 'all'
    check (visibility in ('all', 'leads', 'groups')),
  group_ids bigint[] not null default '{}',
  plannable boolean not null default true,
  public_link boolean not null default true,
  index integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists song_collections_tenant_idx
  on public.song_collections (tenant_id);

alter table public.songs
  add column if not exists collection_id bigint null
    references public.song_collections(id) on delete set null;

create index if not exists songs_collection_idx
  on public.songs (collection_id);

-- May the current reader see Sammlung [p_collection_id]? null = Repertoire.
create or replace function public.song_collection_visible(p_collection_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select p_collection_id is null or exists (
    select 1
    from song_collections c
    where c.id = p_collection_id
      and (
        -- Visible to all: every member; anonymous readers only when the
        -- Sammlung is part of the public Werke link.
        (c.visibility = 'all' and (auth.uid() is not null or c.public_link))
        -- Leads of the owning tenant or of a tenant synced to it.
        or exists (
          select 1
          from "tenantUsers" tu
          join tenants t on t.id = tu."tenantId"
          where tu."userId" = auth.uid()::text
            and tu.role in (1, 3, 5)
            and (tu."tenantId" = c.tenant_id or t.song_source_tenant_id = c.tenant_id)
        )
        -- Certain groups: the reader plays in one of them (by group name,
        -- active persons of the owning or a synced tenant).
        or (
          c.visibility = 'groups'
          and exists (
            select 1
            from player p
            join tenants t on t.id = p."tenantId"
            join instruments own on own.id = p.instrument
            join instruments g on g.id = any (c.group_ids)
            where p."appId" = auth.uid()::text
              and p."left" is null
              and (p."tenantId" = c.tenant_id or t.song_source_tenant_id = c.tenant_id)
              and lower(trim(own.name)) = lower(trim(g.name))
          )
        )
      )
  );
$$;

revoke all on function public.song_collection_visible(bigint) from public;
grant execute on function public.song_collection_visible(bigint) to anon, authenticated;

-- songs: only rows of a visible Sammlung (AND-ed with the existing policies).
drop policy if exists "songs_collection_visibility" on public.songs;
create policy "songs_collection_visibility"
  on public.songs
  as restrictive
  for select
  to anon, authenticated
  using (public.song_collection_visible(collection_id));

-- song_collections: read like song_categories (own and synced tenants),
-- each row only when visible; write by admins/responsibles (1, 5) of the
-- owning tenant or of a tenant synced to it.
alter table public.song_collections enable row level security;

drop policy if exists "users_select_song_collections" on public.song_collections;
create policy "users_select_song_collections"
  on public.song_collections
  for select
  to authenticated
  using (
    tenant_id in (
      select tu."tenantId" from "tenantUsers" tu where tu."userId" = auth.uid()::text
      union
      select t.song_source_tenant_id
      from tenants t
      join "tenantUsers" tu on tu."tenantId" = t.id
      where tu."userId" = auth.uid()::text and t.song_source_tenant_id is not null
    )
    and public.song_collection_visible(id)
  );

drop policy if exists "admins_manage_song_collections" on public.song_collections;
create policy "admins_manage_song_collections"
  on public.song_collections
  for all
  to authenticated
  using (
    tenant_id in (
      select tu."tenantId" from "tenantUsers" tu
      where tu."userId" = auth.uid()::text and tu.role in (1, 5)
      union
      select t.song_source_tenant_id
      from tenants t
      join "tenantUsers" tu on tu."tenantId" = t.id
      where tu."userId" = auth.uid()::text
        and tu.role in (1, 5)
        and t.song_source_tenant_id is not null
    )
  )
  with check (
    tenant_id in (
      select tu."tenantId" from "tenantUsers" tu
      where tu."userId" = auth.uid()::text and tu.role in (1, 5)
      union
      select t.song_source_tenant_id
      from tenants t
      join "tenantUsers" tu on tu."tenantId" = t.id
      where tu."userId" = auth.uid()::text
        and tu.role in (1, 5)
        and t.song_source_tenant_id is not null
    )
  );

-- A Werk may only point to a Sammlung of its own song tenant.
create or replace function public.songs_collection_same_tenant()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.collection_id is not null and not exists (
    select 1 from song_collections c
    where c.id = new.collection_id and c.tenant_id = new."tenantId"
  ) then
    raise exception 'collection % does not belong to tenant %', new.collection_id, new."tenantId";
  end if;
  return new;
end;
$$;

drop trigger if exists songs_collection_same_tenant on public.songs;
create trigger songs_collection_same_tenant
  before insert or update of collection_id on public.songs
  for each row execute function public.songs_collection_same_tenant();
